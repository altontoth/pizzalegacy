# package_windows_zip.ps1 - Package the Windows build into a distributable ZIP
#
# Usage: .\tools\package_windows_zip.ps1 -BuildDir <build_dir> -Version <version>
#
#   BuildDir   path to cmake build output (e.g. build\release)
#   Version    version string for the filename (e.g. 0.0.2)
#
# Run from project root. The executable must already be built.

param(
    [Parameter(Mandatory=$true)]
    [string]$BuildDir,
    [Parameter(Mandatory=$true)]
    [string]$Version
)

$ErrorActionPreference = "Stop"

$ExeName = "Pizza Legacy.exe"
$OutDir  = "PizzaLegacy_v${Version}_win64"
$ZipName = "${OutDir}.zip"

# DLLs that vcpkg places next to the executable in the build output dir
$WantedDlls = @(
    "ADLMIDI.dll",
    "libpng16.dll",
    "SDL2.dll",
    "zlib1.dll",
    "zstd.dll",
    "libzstd.dll"
)

# Check executable exists
$ExePath = Join-Path $BuildDir $ExeName
if (-not (Test-Path $ExePath)) {
    Write-Error "ERROR: Executable not found: $ExePath"
    exit 1
}

# Clean and recreate output directory
if (Test-Path $OutDir) { Remove-Item -Recurse -Force $OutDir }
New-Item -ItemType Directory -Path $OutDir | Out-Null

# Copy executable
Copy-Item $ExePath $OutDir
Write-Host "Copied: $ExeName"

# Copy DLLs found in the build directory
foreach ($dll in $WantedDlls) {
    $src = Join-Path $BuildDir $dll
    if (Test-Path $src) {
        Copy-Item $src $OutDir
        Write-Host "Copied: $dll"
    }
}

# Copy README (generated by CMake into build dir)
$ReadmeSrc = Join-Path $BuildDir "dist\README-Windows.txt"
if (Test-Path $ReadmeSrc) {
    Copy-Item $ReadmeSrc (Join-Path $OutDir "README.txt")
    Write-Host "Copied: README.txt"
}

# Copy licenses
$LicensesDir = "LICENSES"
if (Test-Path $LicensesDir) {
    Copy-Item -Recurse $LicensesDir (Join-Path $OutDir "LICENSES")
    Write-Host "Copied: LICENSES\"
}
$GplSrc = Join-Path $LicensesDir "GPL-3.0-or-later.txt"
if (Test-Path $GplSrc) {
    Copy-Item $GplSrc (Join-Path $OutDir "LICENSE.txt")
    Write-Host "Copied: LICENSE.txt"
}

# Create ZIP
if (Test-Path $ZipName) { Remove-Item $ZipName }
Compress-Archive -Path $OutDir -DestinationPath $ZipName
Remove-Item -Recurse -Force $OutDir

Write-Host "Done: $ZipName"
